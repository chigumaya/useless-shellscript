_(){                                 # シェル関数の定義
  : ${__:=@}                         # 初期値設定 ($__ が未定義なら"@"を代入)
  echo ${#__}                        # 出力
  ___=$@$__                          # ふたつ前の値とひとつ前の値を結合
  __=$@                              # 引数を変数に保存
  ____=.$____                        # カウンタをインクリメント
  [ $____ = .......... ] || _ $___   # カウンタが10未満なら再帰
}
_ :                                  # シェル関数の呼び出し
