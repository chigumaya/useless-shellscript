_(){
  : ${__:=@}
  # echo ${#__}                                 # 出力はコメントアウト
  ___=$@$__
  __=$@
  ____=.$____
  [ $____ = ...................... ] || _ $___  # ループ回数を増やす
}
_ :

# 以下を追加
L=(v-1 h1 v1 h-1)       # 進行方向と線分の長さ
:(){
    echo ${L[i%4]}
    ((i+=++n%2?1:-1))   # 先頭からの位置によって進行方向を変える
}
@(){
    echo ${L[i%4]}
    ((++n))             # 方向転換しない
}
# 関数の羅列を eval で実行し、その結果を取り込んだものを SVG画像として出力
cat <<_EOF_
<svg xmlns="http://www.w3.org/2000/svg" width="600" height="430">
  <path d="M10 420 $(eval "$(echo $__ | fold -1)")" fill="none" stroke="black"/>
</svg>
_EOF_
